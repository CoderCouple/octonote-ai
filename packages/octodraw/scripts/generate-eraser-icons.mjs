// Bundles icons/eraser/*.svg into src/icons/generated-eraser.ts (loaded lazily
// by loadEraserIcons). See icons/eraser/NOTICE.md for provenance.
// Run with `pnpm icons:eraser`.
//
// Each icon is stored as [viewBox, root presentation attributes, inner markup]
// so it can be drawn inline: monochrome icons (Lucide's currentColor strokes,
// Simple Icons' unfilled paths) then follow the node color and the theme,
// while multicolor vendor icons keep their own fills. Markup is sanitized:
// scripts, event handlers, external references and <title>s are removed.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { inlineSvg } from './svg-inline.mjs';

const dir = new URL('../icons/eraser/', import.meta.url);
const icons = {};
let skipped = 0;
for (const file of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  const entry = inlineSvg(readFileSync(new URL(file, dir), 'utf8'));
  if (entry) icons[file.slice(0, -4)] = entry;
  else skipped++;
}
writeFileSync(
  new URL('../src/icons/generated-eraser.ts', import.meta.url),
  `// Generated by scripts/generate-eraser-icons.mjs — do not edit.
// Eraser's icon artwork, temporary: see icons/eraser/NOTICE.md.
export const ERASER_ICONS: Record<string, [viewBox: string, attrs: Record<string, string>, body: string]> = ${JSON.stringify(icons)};
`,
);
console.log(`eraser icons: ${Object.keys(icons).length}${skipped ? ` (skipped ${skipped} unparseable)` : ''}`);
