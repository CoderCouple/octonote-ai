// Builds src/icons/generated.ts so only the icons we ship end up in the bundle.
// Run with `pnpm icons`.
//
// Sources:
// - scripts/icon-catalog.mjs: curated aliases (server, postgres, kafka, …)
// - scripts/eraser-icon-names.json: every icon name Eraser accepts, by section,
//   from https://docs.eraser.io/icons. Names only — no Eraser artwork is used.
//   "General" names are Lucide's, "Tech logos" are matched against Simple
//   Icons, and cloud/k8s/networking names are resolved at runtime to tinted
//   generic glyphs (see src/icons/resolve.ts).
import { readFileSync, writeFileSync } from 'node:fs';
import * as lucide from 'lucide';
import * as simpleIcons from 'simple-icons';
import { BRANDS, GENERIC } from './icon-catalog.mjs';

const eraser = JSON.parse(readFileSync(new URL('./eraser-icon-names.json', import.meta.url), 'utf8'));
const missing = [];
const pascal = (name) => name.replace(/(^|[-.])([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const node = (exportName) => lucide[exportName]?.map(([tag, attrs]) => [tag, attrs]);

// Two outputs: a small core (curated aliases, bundled eagerly) and the full
// catalog (every Eraser name we can match, loaded lazily by the resolver).
const generic = {};
for (const [name, exportName] of Object.entries(GENERIC)) {
  const icon = node(exportName);
  if (icon) generic[name] = icon;
  else missing.push(`lucide:${exportName} (${name})`);
}
const coreGeneric = { ...generic };
let generalMatched = 0;
for (const name of eraser.General) {
  if (generic[name]) {
    generalMatched++;
    continue;
  }
  const icon = node(pascal(name));
  if (icon) {
    generic[name] = icon;
    generalMatched++;
  }
}

// Brand (Simple Icons) logos: curated aliases plus Eraser "Tech logos" matched by slug or title.
const all = Object.values(simpleIcons).filter((i) => i && i.slug);
const normalize = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '');
const bySlug = new Map(all.map((i) => [i.slug, i]));
const byTitle = new Map(all.map((i) => [normalize(i.title), i]));
const brands = {};
const brandAliases = {};
const addBrand = (name, icon) => {
  brands[icon.slug] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path };
  if (name !== icon.slug) brandAliases[name] = icon.slug;
};
for (const [name, slug] of Object.entries(BRANDS)) {
  const icon = bySlug.get(slug);
  if (icon) addBrand(name, icon);
  else missing.push(`simple-icons:${slug} (${name})`);
}
const coreBrands = { ...brands };
const coreBrandAliases = { ...brandAliases };
let logosMatched = 0;
for (const name of eraser['Tech logos']) {
  if (generic[name] || brandAliases[name] || brands[name]) {
    logosMatched++;
    continue;
  }
  const key = normalize(name);
  // Eraser names often carry a product suffix Simple Icons drops (cursor-ide, deno-deploy, anime-js, bunny-net).
  const stem = normalize(name.replace(/-(ide|deploy)$/, ''));
  const icon =
    bySlug.get(name) ??
    bySlug.get(key) ??
    byTitle.get(key) ??
    bySlug.get(stem) ??
    byTitle.get(stem) ??
    bySlug.get(`${key}dotjs`) ??
    bySlug.get(normalize(name.replace(/-(js|net)$/, (m) => `dot${m.slice(1)}`))) ??
    bySlug.get(`apache${key}`);
  if (icon) {
    addBrand(name, icon);
    logosMatched++;
  }
}

const cloudNames = ['AWS', 'Google Cloud', 'Azure', 'Oracle Cloud', 'Kubernetes', 'Networking'].flatMap((s) => eraser[s] ?? []);

const header = (what) => `// Generated by scripts/generate-icons.mjs — do not edit. ${what}
// Generic icons: Lucide (ISC License, https://lucide.dev). Brand icons: Simple Icons (CC0-1.0, https://simpleicons.org).
// Brand logos are trademarks of their owners. Icon names follow https://docs.eraser.io/icons.
import type { IconCatalog } from './types';
`;
const without = (all, core) => Object.fromEntries(Object.entries(all).filter(([k]) => !(k in core)));
writeFileSync(
  new URL('../src/icons/generated-core.ts', import.meta.url),
  header('Curated icons, bundled eagerly.') + `
export const CORE_ICONS: IconCatalog = ${JSON.stringify({ generic: coreGeneric, brands: coreBrands, brandAliases: coreBrandAliases, cloudNames: [] })};
`,
);
writeFileSync(
  new URL('../src/icons/generated-full.ts', import.meta.url),
  header('Every matched Eraser icon name; loaded lazily (see loadFullIconCatalog).') + `
export const FULL_ICONS: IconCatalog = ${JSON.stringify({ generic: without(generic, coreGeneric), brands: without(brands, coreBrands), brandAliases: without(brandAliases, coreBrandAliases), cloudNames })};
`,
);
console.log(`generic: ${Object.keys(generic).length} (Eraser General ${generalMatched}/${eraser.General.length})`);
console.log(`brands: ${Object.keys(brands).length} (Eraser Tech logos ${logosMatched}/${eraser['Tech logos'].length})`);
console.log(`cloud/k8s/networking names: ${cloudNames.length}`);
if (missing.length) console.log(`curated entries missing upstream (skipped): ${missing.join(', ')}`);
