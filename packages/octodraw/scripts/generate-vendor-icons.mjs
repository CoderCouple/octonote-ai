// Bundles licensed vendor icon packs from icons/vendor/<provider>/*.svg
// (imported by scripts/import-*-icons.mjs) into src/icons/generated-vendor.ts,
// loaded lazily by loadVendorIcons(). Vendor icons win over Eraser's artwork.
// Run with `pnpm icons:vendor`.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { inlineSvg } from './svg-inline.mjs';

const root = new URL('../icons/vendor/', import.meta.url);
const icons = {};
const counts = {};
for (const provider of existsSync(root) ? readdirSync(root).filter((d) => statSync(new URL(d, root)).isDirectory()) : []) {
  const dir = new URL(`${provider}/`, root);
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
    const entry = inlineSvg(readFileSync(new URL(file, dir), 'utf8'));
    if (!entry) continue;
    icons[file.slice(0, -4)] = entry;
    counts[provider] = (counts[provider] ?? 0) + 1;
  }
}
writeFileSync(
  new URL('../src/icons/generated-vendor.ts', import.meta.url),
  `// Generated by scripts/generate-vendor-icons.mjs — do not edit.
// Licensed vendor icons; see icons/vendor/*/SOURCE.md.
export const VENDOR_ICONS: Record<string, [viewBox: string, attrs: Record<string, string>, body: string]> = ${JSON.stringify(icons)};
`,
);
console.log(`vendor icons: ${Object.entries(counts).map(([p, n]) => `${p} ${n}`).join(', ') || 'none'}`);
