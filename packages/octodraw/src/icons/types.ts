export type IconElement = [tag: string, attributes: Record<string, string>];

export type IconDef =
  /** Outline icon drawn with the current stroke color on a 24×24 grid. */
  | { kind: 'stroke'; title: string; elements: IconElement[]; viewBox?: string }
  /** Single-path logo filled with its brand color on a 24×24 grid. */
  | { kind: 'brand'; title: string; path: string; color: string; viewBox?: string }
  /** An image (e.g. a licensed vendor SVG supplied by the host), drawn as-is. */
  | { kind: 'image'; title: string; href: string }
  /**
   * Trusted, pre-sanitized SVG markup drawn inline. Monochrome artwork
   * (currentColor / unfilled paths) takes the node's tint; explicit fills win.
   */
  | { kind: 'inline'; title: string; viewBox: string; attrs: Record<string, string>; body: string };

export interface ResolvedIcon {
  icon: IconDef;
  /** Tint for stroke icons (e.g. the cloud provider's color); undefined means the theme default. */
  tint?: string;
}

/** Host-supplied icon lookup. Return undefined to fall through to the built-in catalog. */
export type IconResolver = (name: string) => IconDef | undefined;

/** Icon data as generated by scripts/generate-icons.mjs. */
export interface IconCatalog {
  generic: Record<string, IconElement[]>;
  brands: Record<string, { title: string; hex: string; path: string }>;
  brandAliases: Record<string, string>;
  /** Eraser's cloud/k8s/networking names, resolved to tinted generic glyphs. */
  cloudNames: string[];
}
